const sources = new WeakMap();

export function translateStudioText(locale, text) {
  if (locale === 'fr') return text;
  const pair = translations[text];
  if (!pair) return text;
  return pair[locale === 'zh-CN' ? 1 : 0];
}
export function applyStudioLocale(locale, root = document.querySelector('[data-view="studio"]')) {
  if (!root) return;
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  while (walker.nextNode()) {
    const node = walker.currentNode;
    const parent = node.parentElement;
    if (!parent || ['SCRIPT', 'STYLE', 'CODE'].includes(parent.tagName)) continue;
    if (!sources.has(node)) sources.set(node, node.nodeValue);
    const original = sources.get(node);
    const core = original.trim();
    if (!core) continue;
    const before = original.slice(0, original.indexOf(core));
    const after = original.slice(original.indexOf(core) + core.length);
    node.nodeValue = before + translateStudioText(locale, core) + after;
  }
}
